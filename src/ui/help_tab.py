import streamlit as st

from src.config import TOM_MAX

# Курс конвертации TRY → RUB (синхронизирован с src/ui/predict.py)
TRY_TO_RUB = 1.73


def render(meta):
    st.header("Справка")

    try:
        st.markdown(f"""
        ### О приложении
        Приложение прогнозирует стоимость объекта недвижимости с помощью
        модели **{meta['model_name']}** ({meta['model_type']}).
        Модель вычисляет цену в турецких лирах (TRY), приложение
        **конвертирует результат в рубли (RUB)** по актуальному курсу
        **1 TRY = {TRY_TO_RUB} RUB**.

        ### Поля ввода
        | Поле | Описание | Влияет на прогноз |
        |---|---|---|
        | **size** | Площадь объекта, м² | ✅ |
        | **building_age** | Возраст здания: `0`, `1`, `2`, `3`, `4`, `5`, `6+` | ✅ |
        | **tom** | Время экспозиции, дней, ≤ {TOM_MAX} | ⚠ слабо |
        | **sub_type** | Тип жилья: New / Secondary | ⚠ слабо |
        | **heating_type** | Отопление: Central / Individual / None | ⚠ слабо |
        | **city** | Город | ❌ не влияет |
        | **district_grouped** | Район | ❌ не влияет |
        | **room_count** | Количество комнат | ❌ не влияет |

        **Признаки, помеченные ❌**, включены в форму для полноты
        характеристик, но **не влияют на прогноз** в текущей версии
        модели (см. «Ограничения»).

        ### Почему TOM ограничен значением {TOM_MAX}
        Признак `tom` был ограничен сверху (winsorization 99-й перцентиль ≈ {TOM_MAX}).
        Значения выше {TOM_MAX} **не различаются моделью**.

        ### Почему возраст здания представлен категориями `0`–`5` и `6+`
        В исходных данных `building_age` содержит и числа, и диапазоны.
        При обучении применялось `pd.to_numeric(..., errors='coerce').fillna(0)` —
        диапазоны превращались в `0`. В форме они объединены в `6+`.

        ### Почему город, район и количество комнат не влияют
        | Признак | Причина |
        |---|---|
        | **city** | Пороги сплитов дерева (`16,24`, `16,45`) лежат **выше** максимального значения `city_te` в реальных данных (~15,5). |
        | **district_grouped** | Feature importance 0,3%. |
        | **room_count** | Feature importance 2,6%, **ноль сплитов** в первых узлах. |
        | **price_currency** (убран) | Feature importance 0,04%, в данных — константа. |

        **Причина:** рассинхрон артефактов — модель обучена на синтетических
        данных, а `target_encoders.pkl` собран на реальном датасете.

        ### Модель и метрики
        - Модель: `{meta['model_type']}`
        - R² (log-шкала): **{meta['metrics']['R2_log']:.3f}**
        - R² (исходная шкала): **{meta['metrics']['R2_try']:.3f}**
        - MAPE: **{meta['metrics']['MAPE_pct']:.2f}%**
        - Объём выборки: {meta['dataset_size']} объектов

        ### В какой валюте выводится прогноз
        Модель обучена на ценах в **турецких лирах (TRY)** — в этих единицах
        и вычисляется прогноз. Приложение **конвертирует результат в рубли (RUB)**
        по актуальному курсу:

        > **1 TRY = {TRY_TO_RUB} RUB**

        Курс задан константой `TRY_TO_RUB` в `src/ui/predict.py`. Диапазон
        ошибки (±MAPE) также выводится **в рублях**, так как рассчитывается
        от уже сконвертированной цены.

        В разделе «Дашборд» статистика по сырому датасету показана
        **в турецких лирах** — это исходные данные без конвертации.

        ### Ограничения
        - Модель обучена на исторических данных турецкого рынка.
        - **Рассинхрон артефактов:** модель обучена на синтетических данных,
          `target_encoders.pkl` собран на реальном датасете. Категориальные
          признаки (`city`, `room_count`, `district_grouped`) фактически
          не используются моделью.
        - **Возраст здания:** диапазонные категории в обучении приводились к `0`.
        - **TOM:** значения выше {TOM_MAX} не различаются моделью.
        - **Курс конвертации TRY → RUB фиксирован** ({TRY_TO_RUB}) и не
          обновляется автоматически. Для реального использования требуется
          актуальный курс из API.
        - Модель не учитывает состояние ремонта, этаж, инфраструктуру.
        - Диапазон ошибки рассчитан как ±MAPE от точечного прогноза.

        ---
        **Авторы:** Руднев И.С. и Гумеров А.А. · **Версия:** 2.3 · **Дата:** 09.2026
        """)
    except Exception as e:
        st.error(f"Не удалось отобразить справку: {e}")

    with st.expander("Технические детали пайплайна"):
        st.code(f"""
Сырые данные (real_estate_data.csv)
  → building_age: строка → to_numeric(...).fillna(0)
    (в приложении: '0'-'5' → 0-5, '6+' → 6)
  → tom: clamp(0, {TOM_MAX})
  → address → city, district_grouped
  → Target Encoding: city, room_count, district_grouped
  → One-Hot: sub_type, heating_type, price_currency
  → StandardScaler по колонкам: size, building_age, tom
  → GradientBoostingRegressor
  → np.expm1 → цена (TRY)
  → × {TRY_TO_RUB} → цена (RUB)
        """, language="text")